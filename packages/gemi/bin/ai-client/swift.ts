import { type AgentModel, type NamedType, type Property, type TypeRef, camelCase } from "./model";

/**
 * The model as Swift, for `GemiChat`.
 *
 * Everything goes inside one `enum` named for the agent, which is both the
 * `AgentSchema` a `ChatSession` is generic over and a namespace: two agents in
 * one app can each have a `SearchInput` without a collision.
 */
export function renderSwift(agent: AgentModel): string {
  const lines: string[] = [];
  const emit = (line = "") => lines.push(line);

  emit(`// Generated by \`gemi ai:generate-client\` from ${agent.source}.`);
  emit("// Do not edit: change the agent and run the command again.");
  emit();
  emit("import GemiChat");
  emit();
  emit(`public enum ${agent.name}: AgentSchema {`);
  emit(`  public typealias Output = ${swiftType(agent.output)}`);

  const cases = caseNames(agent.tools.map((tool) => tool.name));
  const tools = agent.tools.map((tool, index) => ({ ...tool, case: cases[index]! }));

  const views = [
    {
      name: "ToolCall",
      raw: "ToolCallPart",
      argument: "part",
      method: "toolCall",
      typed: (tool: (typeof tools)[number]) =>
        `TypedToolCall<${swiftType(tool.input)}, ${swiftType(tool.progress)}>`,
      failable: false,
    },
    {
      name: "ToolResult",
      raw: "ToolResultPart",
      argument: "part",
      method: "toolResult",
      typed: (tool: (typeof tools)[number]) => `TypedToolResult<${swiftType(tool.output)}>`,
      failable: true,
    },
    {
      name: "Pending",
      raw: "PendingToolCall",
      argument: "call",
      method: "pending",
      typed: (tool: (typeof tools)[number]) =>
        `TypedPendingCall<${swiftType(tool.input)}, ${swiftType(tool.output)}>`,
      failable: false,
    },
  ];

  for (const view of views) {
    emit();
    emit(`  public enum ${view.name}: Sendable, Hashable {`);
    for (const tool of tools) emit(`    case ${escape(tool.case)}(${view.typed(tool)})`);
    emit("    /// A tool this file does not know — added since it was generated, or a");
    emit("    /// skill — or a payload that no longer decodes.");
    emit(`    case unknown(${view.raw})`);
    emit("  }");
  }

  for (const view of views) {
    const argument = view.argument;
    emit();
    emit(`  public static func ${view.method}(_ ${argument}: ${view.raw}) -> ${view.name} {`);
    if (tools.length === 0) {
      emit(`    .unknown(${argument})`);
    } else {
      emit(`    switch ${argument}.name {`);
      for (const tool of tools) {
        const typed = view.typed(tool).replace(/<.*>$/, "");
        const value = view.failable
          ? `${view.typed(tool)}(${argument}).map(${view.name}.${escape(tool.case)}) ?? .unknown(${argument})`
          : `.${tool.case}(${typed}(${argument}))`;
        emit(`    case ${JSON.stringify(tool.name)}: ${value}`);
      }
      emit(`    default: .unknown(${argument})`);
      emit("    }");
    }
    emit("  }");
  }

  for (const type of agent.types) {
    emit();
    for (const line of renderType(type)) emit(line === "" ? "" : `  ${line}`);
  }

  emit("}");
  return `${lines.join("\n")}\n`;
}

function swiftType(type: TypeRef): string {
  switch (type.kind) {
    case "string":
      return "String";
    case "number":
      return "Double";
    case "boolean":
      return "Bool";
    case "json":
      return "JSONValue";
    case "never":
      return "Never";
    case "array":
      return `[${swiftType(type.item)}]`;
    case "map":
      return `[String: ${swiftType(type.value)}]`;
    case "nullable":
      return `${swiftType(type.inner)}?`;
    case "named":
      return type.name;
  }
}

function renderType(type: NamedType): string[] {
  switch (type.kind) {
    case "object":
      return renderStruct(type.name, type.properties);
    case "enum":
      return renderEnum(type.name, type.values);
    case "union":
      return renderUnion(type.name, type.discriminant, type.variants);
  }
}

function renderStruct(name: string, properties: Property[]): string[] {
  const names = uniqueIdentifiers(properties.map((property) => property.key));
  const fields = properties.map((property, index) => {
    const base = swiftType(property.type);
    // Absent and null both read back as `nil`: one optional, not two.
    const type = property.optional && property.type.kind !== "nullable" ? `${base}?` : base;
    return { ...property, name: names[index]!, swiftType: type };
  });
  const lines = [`public struct ${name}: Codable, Hashable, Sendable {`];
  for (const field of fields) lines.push(`  public var ${escape(field.name)}: ${field.swiftType}`);

  if (fields.length > 0) lines.push("");
  const parameters = fields.map(
    (field) =>
      `${escape(field.name)}: ${field.swiftType}${field.swiftType.endsWith("?") ? " = nil" : ""}`,
  );
  if (parameters.length === 0) {
    lines.push("  public init() {}");
  } else {
    const oneLine = `  public init(${parameters.join(", ")}) {`;
    if (oneLine.length <= 98) {
      lines.push(oneLine);
    } else {
      lines.push("  public init(");
      parameters.forEach((parameter, index) =>
        lines.push(`    ${parameter}${index < parameters.length - 1 ? "," : ""}`),
      );
      lines.push("  ) {");
    }
    for (const field of fields) lines.push(`    self.${field.name} = ${escape(field.name)}`);
    lines.push("  }");
  }

  // The synthesised `encode` leaves a `nil` out, which is right for a key that
  // may be absent and wrong for one that must be present as `null`: the
  // server's schema requires it, and rejects the answer that omits it.
  const nullRequired = fields.some((field) => !field.optional && field.type.kind === "nullable");
  const renamed = fields.some((field) => field.name !== field.key);
  if (nullRequired || renamed) {
    lines.push("");
    lines.push("  private enum CodingKeys: String, CodingKey {");
    for (const field of fields) {
      lines.push(
        field.name === field.key
          ? `    case ${escape(field.name)}`
          : `    case ${escape(field.name)} = ${JSON.stringify(field.key)}`,
      );
    }
    lines.push("  }");
  }
  if (nullRequired) {
    lines.push("");
    lines.push("  public func encode(to encoder: Encoder) throws {");
    lines.push("    var container = encoder.container(keyedBy: CodingKeys.self)");
    for (const field of fields) {
      const method = field.optional ? "encodeIfPresent" : "encode";
      // `self.`, as in `init`: a keyword field is `in`, and a bare `in` is not
      // an expression. After a dot it needs no backticks.
      lines.push(`    try container.${method}(self.${field.name}, forKey: .${field.name})`);
    }
    lines.push("  }");
  }
  lines.push("}");
  return lines;
}

function renderEnum(name: string, values: string[]): string[] {
  const names = caseIdentifiers(values);
  const lines = [`public enum ${name}: String, Codable, Hashable, Sendable, CaseIterable {`];
  values.forEach((value, index) => {
    const identifier = names[index]!;
    lines.push(
      identifier === value
        ? `  case ${escape(identifier)}`
        : `  case ${escape(identifier)} = ${JSON.stringify(value)}`,
    );
  });
  lines.push("}");
  return lines;
}

function renderUnion(
  name: string,
  discriminant: string,
  variants: { value: string; type: TypeRef }[],
): string[] {
  const names = caseIdentifiers(variants.map((variant) => variant.value));
  const lines = [`public enum ${name}: Codable, Hashable, Sendable {`];
  variants.forEach((variant, index) =>
    lines.push(`  case ${escape(names[index]!)}(${swiftType(variant.type)})`),
  );
  lines.push("");
  lines.push("  private enum Discriminant: String, CodingKey {");
  lines.push(`    case key = ${JSON.stringify(discriminant)}`);
  lines.push("  }");
  lines.push("");
  lines.push("  public init(from decoder: Decoder) throws {");
  lines.push("    let container = try decoder.container(keyedBy: Discriminant.self)");
  lines.push("    let value = try container.decode(String.self, forKey: .key)");
  lines.push("    switch value {");
  variants.forEach((variant, index) => {
    lines.push(
      `    case ${JSON.stringify(variant.value)}: self = .${names[index]}(try ${swiftType(variant.type)}(from: decoder))`,
    );
  });
  lines.push("    default:");
  lines.push("      throw DecodingError.dataCorruptedError(");
  lines.push(
    `        forKey: .key, in: container, debugDescription: "Unknown ${discriminant} \\"\\(value)\\"")`,
  );
  lines.push("    }");
  lines.push("  }");
  lines.push("");
  lines.push("  public func encode(to encoder: Encoder) throws {");
  lines.push("    switch self {");
  names.forEach((identifier) => {
    lines.push(`    case .${identifier}(let value): try value.encode(to: encoder)`);
  });
  lines.push("    }");
  lines.push("  }");
  lines.push("}");
  return lines;
}

/** Enum case names for the tools, clear of the `unknown` every view has. */
function caseNames(toolNames: string[]): string[] {
  return caseIdentifiers(toolNames, new Set(["unknown"]));
}

/** Case names are always camel-cased, as Swift spells them; the raw value
 *  keeps the wire's spelling. */
function caseIdentifiers(texts: string[], taken = new Set<string>()): string[] {
  return uniqueIdentifiers(texts.map(camelCase), taken);
}

/** Swift identifiers for JSON names. A property keeps its key when the key is
 *  already an identifier, so the common case needs no `CodingKeys`; anything
 *  else is camel-cased, and numbered when two collide. */
function uniqueIdentifiers(texts: string[], taken = new Set<string>()): string[] {
  const used = new Set(taken);
  return texts.map((text) => {
    const base = /^[A-Za-z_][A-Za-z0-9_]*$/.test(text) ? text : camelCase(text);
    let name = base;
    for (let n = 2; used.has(name); n++) name = `${base}${n}`;
    used.add(name);
    return name;
  });
}

const KEYWORDS = new Set(
  (
    "associatedtype class deinit enum extension fileprivate func import init inout internal let " +
    "open operator private precedencegroup protocol public rethrows static struct subscript " +
    "typealias var break case catch continue default defer do else fallthrough for guard if in " +
    "repeat return throw switch where while Any as await false is nil self Self super throws " +
    "true try"
  ).split(" "),
);

function escape(identifier: string): string {
  return KEYWORDS.has(identifier) ? `\`${identifier}\`` : identifier;
}
