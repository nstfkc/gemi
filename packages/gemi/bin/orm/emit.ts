/**
 * `wrap`, typed to reject a partial row at compile time.
 *
 * The parameter is the model's full scalar payload — `Prisma.<M>GetPayload<{}>` —
 * so a `Pick` of it fails to type-check for the ordinary reason that it is
 * missing properties. That single constraint is what lets instances and `select`
 * coexist: a method reading `this.email` can only ever run on a row that
 * actually fetched `email`.
 *
 * The return type intersects the row with the class, so the instance carries both
 * the columns and whatever the application's subclass adds. `this: C` plus
 * `C["prototype"]` is what makes it the *subclass's* instance type rather than
 * the generated base's — `Account.wrap(...)` returns an `Account`, not an
 * `AccountModel`, so a method defined on the subclass is visible on the result.
 *
 * `{ prototype: unknown }` rather than the more obvious
 * `new (...args: never[]) => any`, because `Model`'s constructor is `protected`
 * (which is what stops a directly constructed instance from lying about its
 * columns) and a protected constructor does not satisfy a public construct
 * signature. Constraining on the prototype reads the instance type without
 * caring how — or whether — the class can be constructed from outside.
 *
 * `R` is generic rather than fixed to the payload so a row carrying `include`d
 * relations keeps them in the result type. The constraint still requires *at
 * least* the full scalar set, which is the property that matters.
 */
function wrapOperation(model: string): string {
  const payload = `Prisma.${model}GetPayload<{}>`;
  return `
  static wrap<C extends { prototype: unknown }, R extends ${payload}>(
    this: C,
    row: R,
  ): C["prototype"] & R {
    return (Model.wrap as (row: object) => any).call(this, row);
  }
`;
}

/**
 * Declaration merging, so an instance's *columns* are visible to methods written
 * on the subclass.
 *
 * An `interface` sharing the class's name merges into its instance type, which is
 * what makes this work:
 *
 *     export class User extends UserModel {
 *       get displayName() { return this.name ?? this.email ?? "anonymous" }
 *     }
 *
 * Without it `this.name` does not exist and the entity tier is useless — a
 * wrapper whose methods cannot read the row is not a wrapper. The first version
 * of `wrap` intersected the columns into its *return* type only, which typed the
 * call site correctly and left the class body blind.
 *
 * Emitted as an interface rather than as `declare` fields for two reasons: it
 * reuses Prisma's own payload type instead of re-deriving TypeScript types from
 * the DMMF, so the two cannot drift; and it is zero runtime output, which
 * `declare` also is but less obviously.
 *
 * The honest cost: `new UserModel()` now type-checks as having columns it does
 * not have. These classes are constructed by `wrap` and by nothing else — the
 * fifteen operations return plain objects — so the lie is confined to a
 * constructor call no application has a reason to make.
 */
function instanceShape(model: string): string {
  return `
// Merges the row's columns into the instance type, so a method on a subclass can
// read \`this.email\`. No runtime output.
//
// oxlint flags class/interface merging because TypeScript does not check the
// merged properties are initialised — a directly constructed instance would type
// as carrying every column while holding none. That hazard is closed rather than
// accepted: \`Model\`'s constructor is \`protected\`, so the only way to get an
// instance is \`wrap\`, which assigns a complete row. See bin/orm/emit.ts.
// oxlint-disable-next-line typescript-eslint/no-unsafe-declaration-merging
export interface ${model}Model extends Prisma.${model}GetPayload<{}> {}
`;
}

/**
 * The model's policy types, emitted so an application never writes
 * `ModelPolicy<Prisma.UserWhereInput, Prisma.UserCreateInput, …>` by hand.
 *
 * Two names because the two authoring forms need different things, and one name
 * cannot be both a class to extend and a plain type alias:
 *
 *   static $policies: UserPolicy[] = [{ scope: (ctx) => … }]   // object form
 *   class Tenant extends UserScopedPolicy { … }                // class form
 *
 * The annotation on the object form is load-bearing rather than decorative.
 * TypeScript does not contextually type an initializer from an inherited static
 * declaration, so a bare `static $policies = [{ scope: (ctx) => … }]` leaves
 * `ctx` an implicit `any` — the return type is still checked against the base's
 * declaration, but the author gets no help writing the body. Naming the type is
 * what turns the hook into a typed one.
 *
 * `${model}Policy` is a `type` and `${model}ScopedPolicy` is a class, which is
 * the split their uses actually want. The scoped one *has* to be a class —
 * abstract members are the entire mechanism. The plain one is only ever an
 * annotation (`static $policies: UserPolicy[] = [...]`), and emitting it as a
 * class would put two runtime declarations plus a value import of `Policy` into
 * every generated `models.ts`, once per model, to serve a use nobody has: an
 * author who wants methods without the mandatory write halves extends
 * `Policy<…>` from `gemi/orm` directly.
 */
function policyTypes(model: string): string {
  return `
export type ${model}Policy = ModelPolicy<
  Prisma.${model}WhereInput,
  Prisma.${model}CreateInput,
  Prisma.${model}GetPayload<{}>
>;

// The same shape with \`scope\`, \`onCreate\` and \`onUpdate\` abstract, so a policy
// that scopes cannot omit the write halves. The runtime refuses those
// combinations too — this makes it \`TS2515\` at the class declaration instead of
// an error on the first write that reaches production.
export abstract class ${model}ScopedPolicy extends ScopedPolicy<
  Prisma.${model}WhereInput,
  Prisma.${model}CreateInput,
  Prisma.${model}GetPayload<{}>
> {}
`;
}

function operation(model: string, op: ReadOperation): string {
  const argsType = `Prisma.${model}${op.args}`;
  const returns = op.returns(model);
  // `options` is a *second parameter* rather than a key inside `args`, so
  // `Prisma.${model}${op.args}` keeps describing exactly what the operation
  // accepts. Intersecting every args type with a gemi-specific key would make
  // Prisma's own types wrong about our surface, which is the DX parity this
  // project is built on. It also keeps the flag away from the compiler, so it
  // cannot reach the plan key — which it must not, since it does not change SQL.
  return `
  static ${op.name}<T extends ${argsType}>(
    args${op.required ? "" : "?"}: Subset<T, ${argsType}>,
    options?: ExecOptions,
  ): Promise<${returns}> {
    return this.$exec("${op.name}", args, options) as Promise<${returns}>;
  }
`;
}

/**
 * `count`, whose result depends on whether it was given a `select`.
 *
 * Without one it is a plain `number`. With one it is Prisma's object of
 * per-field counts — `{ _all: 3, email: 2 }`, where each field's number is the
 * rows whose column is *not null*. Both spellings are Prisma's, so the overload
 * is what keeps the return type exact rather than widening it to
 * `number | object` for every caller.
 *
 * `GetScalarType` is Prisma's own mapper for this: it turns the caller's select
 * into the shape of the payload it produces, which is how `count({ select: {
 * email: true } })` narrows to `{ email: number }` and not to the whole model.
 */
function countOperation(model: string): string {
  return `
  static count(args?: Omit<Prisma.${model}CountArgs, "select">): Promise<number>;
  static count<T extends Prisma.${model}CountArgs>(
    args: Prisma.SelectSubset<T, Prisma.${model}CountArgs> & {
      select: NonNullable<T["select"]>;
    },
  ): Promise<Prisma.GetScalarType<T["select"], Prisma.${model}CountAggregateOutputType>>;
  static count(args?: unknown): Promise<unknown> {
    return this.$exec("count", args as never);
  }
`;
}

/**
 * `aggregate` — `_count`, `_avg`, `_sum`, `_min`, `_max` over a filtered set.
 *
 * The payload type is Prisma's `GetXAggregateType<T>`, which is what makes
 * `_max: { position: true }` narrow to `{ _max: { position: number | null } }`
 * rather than to every field of every function. Same rule as everywhere else
 * here: the types are Prisma's own, so narrowing stays exact and there is no
 * second definition of the shape to drift.
 *
 * `groupBy` is beside it now, and its typing is the awkward one.
 *
 * Prisma's `groupBy` signature is not a plain `Subset`: it carries a conditional
 * that reports a *missing* `by` field in `orderBy` as a type error naming the
 * field. Reproducing that machinery would mean copying a large conditional out
 * of the generated client, where it would then be a second definition free to
 * drift from the first — the thing every other operation here avoids.
 *
 * So the args type is Prisma's `${model}GroupByArgs` directly and the return is
 * its `Get${model}GroupByPayload<T>`, which still narrows the payload exactly.
 * The `orderBy`-must-be-in-`by` rule is enforced at runtime instead, with a
 * message naming the field and saying why — see `compile/group-by.ts`. A
 * compile-time error would be better; a *wrong* compile-time error, or a silent
 * one, would be worse than a precise runtime refusal.
 */
function aggregateOperation(model: string): string {
  return `
  static aggregate<T extends Prisma.${model}AggregateArgs>(
    args: Prisma.Subset<T, Prisma.${model}AggregateArgs>,
  ): Promise<Prisma.Get${model}AggregateType<T>> {
    return this.$exec("aggregate", args) as Promise<
      Prisma.Get${model}AggregateType<T>
    >;
  }

  static groupBy<T extends Prisma.${model}GroupByArgs>(
    args: Prisma.Subset<T, Prisma.${model}GroupByArgs>,
  ): Promise<Prisma.Get${model}GroupByPayload<T>> {
    return this.$exec("groupBy", args) as Promise<
      Prisma.Get${model}GroupByPayload<T>
    >;
  }
`;
}

/**
 * The write surface.
 *
 * `create`, `update`, `delete` and `upsert` return a payload narrowed by the
 * caller's `select` / `include`, exactly as the reads do — and, like the
 * `*OrThrow` reads, they never resolve to `null`: Prisma raises when an
 * `update` or a `delete` matches nothing, and `$exec` does the same.
 *
 * The three `*Many` writes return Prisma's `BatchPayload` — `{ count: number }`
 * — rather than rows. Prisma's own `createManyAndReturn` is a separate
 * operation and is not emitted.
 *
 * `args` is required on every one of them: there is no meaningful `create()`
 * with no data, and a `deleteMany()` with no arguments is spelled
 * `deleteMany({})` so that emptying a table stays something you typed on purpose.
 */
const WRITE_OPERATIONS: ReadOperation[] = [
  {
    name: "create",
    args: "CreateArgs",
    returns: (m) => `Prisma.${m}GetPayload<T>`,
    required: true,
  },
  {
    name: "update",
    args: "UpdateArgs",
    returns: (m) => `Prisma.${m}GetPayload<T>`,
    required: true,
  },
  {
    name: "delete",
    args: "DeleteArgs",
    returns: (m) => `Prisma.${m}GetPayload<T>`,
    required: true,
  },
  {
    name: "upsert",
    args: "UpsertArgs",
    returns: (m) => `Prisma.${m}GetPayload<T>`,
    required: true,
  },
];

/** The writes whose result is a count rather than a payload. */
const BATCH_OPERATIONS = [
  { name: "createMany", args: "CreateManyArgs" },
  { name: "updateMany", args: "UpdateManyArgs" },
  { name: "deleteMany", args: "DeleteManyArgs" },
] as const;

function batchOperation(
  model: string,
  op: (typeof BATCH_OPERATIONS)[number],
): string {
  return `
  static ${op.name}(
    args?: Prisma.${model}${op.args},
  ): Promise<{ count: number }> {
    return this.$exec("${op.name}", args) as Promise<{ count: number }>;
  }
`;
}

/**
 * Where `models.ts` type-imports `Prisma` from.
 *
 * `@prisma/client` for every ordinary app, and the default is what keeps the
 * emitted file byte-identical to what it was before this parameter existed.
 *
 * It is a parameter at all because a schema can generate its client somewhere
 * else — `generator client { output = … }` — and then `@prisma/client` is not
 * where its types live. That is not a hypothetical: it is how a repository
 * covers a column one dialect has and the other cannot, which is exactly the
 * position `String[]` is in (#300). One `schema.prisma` cannot carry a scalar
 * list, because Prisma refuses the declaration outright on SQLite, so the
 * second schema needs a second client and the artifacts generated from it have
 * to import that one.
 */
const DEFAULT_CLIENT = "@prisma/client";

export function emitModelsFile(
  schemas: ModelSchema[],
  client: string = DEFAULT_CLIENT,
): string {
  const parts = [
    HEADER,
    `\nimport type { Prisma } from ${JSON.stringify(client)};\n`,
    `import {
  Model,
  ScopedPolicy,
  type ExecOptions,
  type ModelPolicy,
  type PolicyEntry,
} from "gemi/orm";\n`,
    `\nimport * as schema from "./schema";\n`,
    `
// Copied from Prisma's own generated client. It is what makes \`select\` and
// \`include\` narrow the return type: \`T\` is inferred from the literal the
// caller passes, and any key outside the operation's argument type collapses to
// \`never\` rather than being quietly accepted.
type Subset<T, U> = {
  [key in keyof T]: key extends keyof U ? T[key] : never;
};
`,
  ];

  for (const schema of schemas) {
    parts.push(instanceShape(schema.name));
    parts.push(policyTypes(schema.name));
    parts.push(`
export class ${schema.name}Model extends Model {
  static $schema = schema.${schema.name};

  // Narrowed from \`Model\`'s \`PolicyEntry[]\` to this model's own, so a policy
  // written for another model is a type error here rather than a scope compiled
  // against columns that do not exist.
  static $policies?: readonly PolicyEntry<
    Prisma.${schema.name}WhereInput,
    Prisma.${schema.name}CreateInput,
    Prisma.${schema.name}GetPayload<{}>
  >[];
${READ_OPERATIONS.map((op) => operation(schema.name, op)).join("")}${countOperation(
      schema.name,
    )}${aggregateOperation(schema.name)}${WRITE_OPERATIONS.map((op) => operation(schema.name, op)).join(
      "",
    )}${BATCH_OPERATIONS.map((op) => batchOperation(schema.name, op)).join(
      "",
    )}${wrapOperation(schema.name)}}
`);
  }

  return parts.join("");
}

export function emitIndexFile(schemas: ModelSchema[]): string {
  const imports = schemas.map((s) => `  ${s.name}Model,`).join("\n");
  const registrations = schemas
    .map((s) => `register("${s.name}", ${s.name}Model);`)
    .join("\n");

  return `${HEADER}
import { assertSchemaArtifactVersion, register } from "gemi/orm";

import { ARTIFACT_VERSION } from "./schema";
import {
${imports}
} from "./models";

assertSchemaArtifactVersion(ARTIFACT_VERSION);

// Registration is by name, and resolution happens at call time. That is what
// lets two models reference each other without the generated files forming an
// import cycle.
${registrations}

export * from "./models";
export * as schema from "./schema";
`;
}

export interface EmitOptions {
  /** See {@link emitModelsFile}. Defaults to `@prisma/client`. */
  client?: string;
}

export function emitArtifacts(
  models: readonly DMMF.Model[],
  options: EmitOptions = {},
): Record<GeneratedFile, string> {
  const schemas = buildModelSchemas(models);
  return {
    "schema.ts": emitSchemaFile(schemas),
    "models.ts": emitModelsFile(schemas, options.client),
    "index.ts": emitIndexFile(schemas),
  };
}
