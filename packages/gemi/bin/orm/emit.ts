import type { DMMF } from "@prisma/generator-helper";

import {
  SCHEMA_ARTIFACT_VERSION,
  type DefaultSpec,
  type FieldSchema,
  type ModelSchema,
  type RelationSchema,
  type ScalarType,
} from "../../orm/schema";

// Build-time only. This file runs inside the Prisma generator process and may
// import from `@prisma/*` freely; the ORM *runtime* under `packages/gemi/orm/`
// may not, and there is an acceptance test that greps for exactly that.
//
// Everything here is a pure function of the DMMF so the emitters can be unit
// tested with no Prisma CLI and no database, and so running the generator twice
// over an unchanged schema produces a byte-identical file.

export const GENERATED_FILES = ["schema.ts", "models.ts", "index.ts"] as const;
export type GeneratedFile = (typeof GENERATED_FILES)[number];

const HEADER = `// Generated by the gemi ORM generator. Do not edit.
//
// Re-run \`prisma generate\` (or \`prisma migrate dev\`) to refresh this file.
// It is committed on purpose: diffs stay reviewable and CI needs no codegen step.
`;

const SCALAR_TYPES: Record<string, ScalarType> = {
  int: "Int",
  string: "String",
  datetime: "DateTime",
  boolean: "Boolean",
  float: "Float",
  bigint: "BigInt",
  decimal: "Decimal",
  json: "Json",
  bytes: "Bytes",
};

export class UnsupportedSchemaError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "UnsupportedSchemaError";
  }
}

function scalarType(model: string, field: DMMF.Field): ScalarType {
  const mapped = SCALAR_TYPES[field.type.toLowerCase()];
  if (!mapped) {
    throw new UnsupportedSchemaError(
      `${model}.${field.name} has the scalar type '${field.type}', which the ` +
        `gemi ORM generator does not know how to map.`,
    );
  }
  return mapped;
}

function defaultSpec(field: DMMF.Field): DefaultSpec | undefined {
  if (!field.hasDefaultValue || field.default === undefined) return undefined;

  const value = field.default;
  if (typeof value === "object" && !Array.isArray(value)) {
    switch (value.name) {
      case "autoincrement":
      case "cuid":
      case "uuid":
      case "now":
      case "dbgenerated":
        return { kind: value.name };
      default:
        // An unrecognised function default (`auto()`, `nanoid()`, a future
        // addition) still tells the runtime "the database supplies this", which
        // is all iteration 4 needs to know when it omits the column on insert.
        return { kind: "dbgenerated" };
    }
  }

  return { kind: "value", value: value as unknown };
}

function fieldSchema(model: string, field: DMMF.Field): FieldSchema {
  // Key order here is the key order in the emitted file. Keep it stable.
  const schema: FieldSchema = {
    name: field.name,
    column: field.dbName ?? field.name,
    type: field.kind === "enum" ? "String" : scalarType(model, field),
    nullable: !field.isRequired,
    isId: field.isId,
    isUpdatedAt: field.isUpdatedAt === true,
  };

  // Prisma enums travel as strings on the wire, so `type` stays `"String"` and
  // the enum's identity is recorded separately for a later iteration.
  if (field.kind === "enum") schema.enum = field.type;

  const def = defaultSpec(field);
  if (def) schema.default = def;

  return schema;
}

function relationSchema(
  field: DMMF.Field,
  joinTable: RelationSchema["joinTable"],
): RelationSchema {
  const relation: RelationSchema = {
    name: field.name,
    model: field.type,
    kind: field.isList ? "many" : "one",
    relationName: field.relationName ?? "",
    from: [...(field.relationFromFields ?? [])],
    to: [...(field.relationToFields ?? [])],
    nullable: !field.isRequired,
  };
  if (joinTable) relation.joinTable = joinTable;
  return relation;
}

/**
 * Prisma's implicit many-to-many relations have no join model in the datamodel:
 * both sides are lists holding no foreign key. The table Prisma creates for
 * them is `_<relationName>` with columns `A` and `B`, ordered by the two model
 * names alphabetically. Emitted now, unused until iteration 3.
 */
function implicitJoinTable(
  model: DMMF.Model,
  field: DMMF.Field,
  byRelationName: Map<string, { model: string; field: DMMF.Field }[]>,
): RelationSchema["joinTable"] | undefined {
  if (!field.isList || !field.relationName) return undefined;
  if ((field.relationFromFields ?? []).length > 0) return undefined;

  const sides = byRelationName.get(field.relationName) ?? [];
  if (sides.length !== 2) return undefined;
  if (!sides.every((side) => side.field.isList)) return undefined;

  const [first, second] = [model.name, field.type].sort();
  return { table: `_${field.relationName}`, a: first, b: second };
}

/** Single-field `@unique` plus composite `@@unique`, deduplicated, in order. */
function uniques(model: DMMF.Model): string[][] {
  const seen = new Set<string>();
  const out: string[][] = [];

  const push = (fields: string[]) => {
    // NUL cannot appear in a field name, so it cannot merge two distinct groups.
    const key = fields.join("\u0000");
    if (seen.has(key)) return;
    seen.add(key);
    out.push(fields);
  };

  for (const field of model.fields) {
    if (field.kind !== "object" && field.isUnique) push([field.name]);
  }
  for (const group of model.uniqueFields) push([...group]);

  return out;
}

export function buildModelSchema(
  model: DMMF.Model,
  byRelationName: Map<string, { model: string; field: DMMF.Field }[]>,
): ModelSchema {
  const fields: Record<string, FieldSchema> = {};
  const relations: Record<string, RelationSchema> = {};

  for (const field of model.fields) {
    if (field.kind === "object") {
      relations[field.name] = relationSchema(
        field,
        implicitJoinTable(model, field, byRelationName),
      );
      continue;
    }
    if (field.kind === "unsupported") {
      // Prisma's own client omits `Unsupported(...)` columns from its result
      // types, so omitting them keeps our result shape identical to Prisma's.
      continue;
    }
    // A list of scalars is Postgres-only and needs array decoding; iteration 2
    // handles it. Skipping silently would change the result shape, so refuse.
    if (field.isList) {
      throw new UnsupportedSchemaError(
        `${model.name}.${field.name} is a scalar list, which the gemi ORM ` +
          `does not support yet.`,
      );
    }
    fields[field.name] = fieldSchema(model.name, field);
  }

  const primaryKey = model.primaryKey
    ? [...model.primaryKey.fields]
    : model.fields.filter((field) => field.isId).map((field) => field.name);

  return {
    name: model.name,
    table: model.dbName ?? model.name,
    fields,
    primaryKey,
    uniques: uniques(model),
    relations,
  };
}

export function buildModelSchemas(
  models: readonly DMMF.Model[],
): ModelSchema[] {
  const byRelationName = new Map<
    string,
    { model: string; field: DMMF.Field }[]
  >();
  for (const model of models) {
    for (const field of model.fields) {
      if (field.kind !== "object" || !field.relationName) continue;
      const sides = byRelationName.get(field.relationName) ?? [];
      sides.push({ model: model.name, field });
      byRelationName.set(field.relationName, sides);
    }
  }

  // Sorted by name rather than left in declaration order, so reordering the
  // Prisma schema does not churn the generated diff.
  return [...models]
    .sort((a, b) => (a.name < b.name ? -1 : a.name > b.name ? 1 : 0))
    .map((model) => buildModelSchema(model, byRelationName));
}

// `JSON.stringify` is the serializer on purpose: the emitted metadata is plain
// data, the key order is the insertion order built above, and `undefined`
// members drop out — so the output is deterministic by construction rather than
// by a formatting convention nobody re-checks.
function literal(value: unknown): string {
  return JSON.stringify(value, null, 2);
}

export function emitSchemaFile(schemas: ModelSchema[]): string {
  const parts = [
    HEADER,
    `\nimport type { ModelSchema } from "gemi/orm";\n`,
    `\n// Compared against the runtime's own constant when this artifact is\n`,
    `// registered, so a stale directory fails with "re-run prisma generate"\n`,
    `// rather than with a TypeError inside the compiler.\n`,
    `export const ARTIFACT_VERSION = ${SCHEMA_ARTIFACT_VERSION};\n`,
  ];

  for (const schema of schemas) {
    parts.push(
      `\nexport const ${schema.name}: ModelSchema = ${literal(schema)};\n`,
    );
  }

  return parts.join("");
}

export function emitModelsFile(schemas: ModelSchema[]): string {
  const parts = [
    HEADER,
    `\nimport type { Prisma } from "@prisma/client";\n`,
    `import { Model } from "gemi/orm";\n`,
    `\nimport * as schema from "./schema";\n`,
    `
// Copied from Prisma's own generated client. It is what makes \`select\` and
// \`include\` narrow the return type: \`T\` is inferred from the literal the
// caller passes, and any key outside the operation's argument type collapses to
// \`never\` rather than being quietly accepted.
type Subset<T, U> = {
  [key in keyof T]: key extends keyof U ? T[key] : never;
};
`,
  ];

  for (const schema of schemas) {
    const name = schema.name;
    parts.push(`
export class ${name}Model extends Model {
  static $schema = schema.${name};

  static findMany<T extends Prisma.${name}FindManyArgs>(
    args?: Subset<T, Prisma.${name}FindManyArgs>,
  ): Promise<Prisma.${name}GetPayload<T>[]> {
    return this.$exec("findMany", args) as Promise<
      Prisma.${name}GetPayload<T>[]
    >;
  }
}
`);
  }

  return parts.join("");
}

export function emitIndexFile(schemas: ModelSchema[]): string {
  const imports = schemas.map((s) => `  ${s.name}Model,`).join("\n");
  const registrations = schemas
    .map((s) => `register("${s.name}", ${s.name}Model);`)
    .join("\n");

  return `${HEADER}
import { assertSchemaArtifactVersion, register } from "gemi/orm";

import { ARTIFACT_VERSION } from "./schema";
import {
${imports}
} from "./models";

assertSchemaArtifactVersion(ARTIFACT_VERSION);

// Registration is by name, and resolution happens at call time. That is what
// lets two models reference each other without the generated files forming an
// import cycle.
${registrations}

export * from "./models";
export * as schema from "./schema";
`;
}

export function emitArtifacts(
  models: readonly DMMF.Model[],
): Record<GeneratedFile, string> {
  const schemas = buildModelSchemas(models);
  return {
    "schema.ts": emitSchemaFile(schemas),
    "models.ts": emitModelsFile(schemas),
    "index.ts": emitIndexFile(schemas),
  };
}
